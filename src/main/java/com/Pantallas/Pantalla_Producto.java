    private void jBGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBGuardarActionPerformed
        String id = jTId.getText().trim();
        String nombre = jTNombre.getText().trim();
        String descripcion = jTDescripcion.getText().trim();

        if (id.isEmpty() || nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El ID y el nombre son obligatorios.",
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        try {
            double precio = Double.parseDouble(jTPrecio.getText().trim().replace(',', '.'));
            int stock = Integer.parseInt(jTStock.getText().trim());
            if (precio < 0 || stock < 0) {
                JOptionPane.showMessageDialog(this, "El precio y el stock no pueden ser negativos.",
                        "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            resultado = new Producto(id, nombre, descripcion, precio, stock);
            dispose();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,
                    "El precio debe ser un número y el stock un número entero.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBGuardarActionPerformed

